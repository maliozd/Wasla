namespace Wasla.Domain.Entities.TenantDb;

/// <summary>
/// One tenant sign-in (password login or signup welcome link), stored in the tenant's own database. A tenant cookie
/// carries the session's id and is accepted only while this row exists for the cookie's user and is not revoked; logout
/// revokes it. The row has no expiry: the cookie ticket's own lifetime (sliding and remember-me) still decides when a
/// session times out. Rows are kept after revocation and after the cookie expires; there is no cleanup yet.
/// </summary>
public sealed class TenantSession
{
    /// <summary>Generated by the server from a cryptographic random source at sign-in. Never log this value.</summary>
    public Guid Id { get; set; }

    /// <summary>The signed-in user (<c>AppUsers.Id</c>).</summary>
    public Guid UserId { get; set; }

    public DateTime CreatedAtUtc { get; set; }

    /// <summary>When logout ended this session. Null while the session may still authenticate.</summary>
    public DateTime? RevokedAtUtc { get; set; }
}
